import test from 'node:test';
import assert from 'node:assert/strict';
import { estimateFileAuthorship, estimateProjectAuthorship } from '../docs/assets/engine/authorship.mjs';
import { scanEntries, textEntries, libsAvailable } from './helpers/scan-helpers.mjs';

const file = (path, content) => ({ path, language: 'javascript', kind: 'source', content });
const body = Array.from({ length: 20 }, (_, i) => `export const v${i} = ${i};`).join('\n');

test('ordinary code is Indeterminate; style alone is never treated as evidence', () => {
  const commented = Array.from({ length: 60 }, (_, i) => `// Step ${i}: explain\nconst x${i} = ${i}; // 🚀 ✅ ⚠`).join('\n');
  for (const content of [body, commented]) {
    const e = estimateFileAuthorship(file('a.js', content));
    assert.equal(e.category, 'indeterminate');
  }
});

test('one residue indicator is insufficient; two independent families give a low-confidence estimate', () => {
  const one = estimateFileAuthorship(file('a.js', `${body}\n// ... rest of the code remains the same\n`));
  assert.equal(one.category, 'indeterminate');
  const two = estimateFileAuthorship(file('b.js', `// Here's the updated code\n${body}\n// ... rest of the code\nconst KEY = "your-api-key-here";\n`));
  assert.equal(two.category, 'ai-assisted');
  assert.equal(two.confidence, 'low');
});

test('declarations, generator markers and contradictions are handled without overclaiming', () => {
  assert.equal(estimateFileAuthorship(file('a.js', `// This file was generated by ChatGPT\n${body}`)).category, 'ai-assisted');
  const gen = estimateFileAuthorship(file('pb.js', `// Code generated by protoc-gen-js. DO NOT EDIT.\n${body}`));
  assert.equal(gen.category, 'indeterminate'); assert.match(gen.note, /conventional code generator/);
  assert.equal(estimateFileAuthorship(file('m.js', `// Generated with Copilot\n// Written by hand, no AI was used\n${body}`)).category, 'mixed');
});

test('project estimate reports heuristic type, distribution, methodology and limitations; never a percentage', () => {
  const p = estimateProjectAuthorship([file('a.js', body), file('b.js', body)], [{ path: 'CLAUDE.md' }]);
  assert.equal(p.estimateType, 'heuristic');
  assert.equal(p.category, 'indeterminate');
  assert.deepEqual(p.workflowArtifacts, ['CLAUDE.md']);
  assert.ok(p.limitations.some(l => /cannot prove authorship/i.test(l)));
  assert.doesNotMatch(JSON.stringify(p), /\d+(?:\.\d+)?\s*%/);
});

test('authorship never changes findings, severities or coverage', { skip: libsAvailable ? false : 'TypeScript libs missing' }, async () => {
  const code = 'export function f(x) { return eval(x); }\n';
  const plain = await scanEntries(textEntries({ 'a.js': code }));
  const flagged = await scanEntries(textEntries({ 'a.js': `// Here's the updated code\n// ... rest of the code\n${code}` }));
  const strip = s => s.findings.map(f => `${f.rule}|${f.severity}|${f.verification}`).sort();
  assert.deepEqual(strip(flagged), strip(plain));
  assert.deepEqual(flagged.coverage.ratios.map(r => [r.id, r.numerator, r.denominator]), plain.coverage.ratios.map(r => [r.id, r.numerator, r.denominator]));
  assert.notEqual(flagged.authorship.files[0]?.category, undefined);
});
