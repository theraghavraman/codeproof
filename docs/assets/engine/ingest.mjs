// File, folder and archive ingestion. Every discovered entry receives a manifest record with an explicit
// status (ingested, skipped or failed) and reason; limits are reported, never applied silently.
import { normalizePath, isIgnoredByPolicy, ignoredRoot, basename } from './paths.mjs';
import { detectLanguage, classifyKind, decodeText, looksBinary, magicType, isBinaryExtension, isArchiveExtension, looksMinified } from './detect.mjs';
import { readZipDirectory, extractEntry, entryRisk, ZipError } from './zip.mjs';
import { throwIfAborted, textEncoder } from './util.mjs';

const GENERATED_HEADER = /(?:@generated\b|\bthis file (?:was|is) (?:auto-?)?generated\b|\bcode generated by\b[^\n]*\bdo not edit\b|\bauto-?generated file\b[^\n]*\bdo not (?:edit|modify)\b|\bgenerated\.\s*do not modify manually\b)/i;
export const INGEST_DEFAULTS = Object.freeze({ maxFiles: 1000, maxFileBytes: 250_000, maxTotalBytes: 14_000_000, ignorePaths: [] });

export function ingestionLimits(policy = {}) {
  return {
    maxFiles: policy.maxFiles ?? INGEST_DEFAULTS.maxFiles,
    maxFileBytes: policy.maxFileBytes ?? INGEST_DEFAULTS.maxFileBytes,
    maxTotalBytes: policy.maxTotalBytes ?? INGEST_DEFAULTS.maxTotalBytes,
    ignorePaths: policy.ignorePaths ?? INGEST_DEFAULTS.ignorePaths,
  };
}

// rawEntries: iterable of { path, size?, read?: () => Promise<Uint8Array|string>, text?: string, isDirectory?, isSymlink?, rejectReason? }
export async function ingestEntries(rawEntries, { policy = {}, signal, onProgress, source = 'upload' } = {}) {
  const limits = ingestionLimits(policy);
  const manifest = [], files = [], limitEvents = [];
  const seen = new Map(), ignoredGroups = new Map();
  let totalBytes = 0, loaded = 0, index = 0;
  const entries = Array.isArray(rawEntries) ? rawEntries : Array.from(rawEntries);
  const record = (r) => { manifest.push({ status: 'skipped', reason: '', warnings: [], ...r }); return r; };
  const noteLimit = (type, detail) => { if (!limitEvents.some(l => l.type === type)) limitEvents.push({ type, detail }); };

  for (const raw of entries) {
    throwIfAborted(signal);
    index++;
    if (index % 50 === 0) onProgress?.({ phase: 'ingest', done: index, total: entries.length });
    const norm = normalizePath(raw.path);
    if (raw.isDirectory) {
      // Directories skipped during a folder walk (for example node_modules) are still reported.
      const rule = norm.ok ? isIgnoredByPolicy(norm.path, limits.ignorePaths) : null;
      if (rule) { const root = ignoredRoot(norm.path, rule); if (!ignoredGroups.has(root)) ignoredGroups.set(root, { path: root, status: 'skipped', kind: 'excluded-directory', reason: `Excluded by policy ignorePaths ("${rule}"); contents not inspected.`, count: 0, size: 0, warnings: ['Contents were not enumerated.'] }); }
      continue;
    }
    if (!norm.ok) { record({ path: String(raw.path ?? ''), rawPath: raw.path, status: 'skipped', reason: `Unsafe path: ${norm.reason}`, size: raw.size ?? null }); continue; }
    if (norm.isDirectory) continue;
    const path = norm.path;
    const base = { path, rawPath: raw.path !== path ? raw.path : undefined, size: raw.size ?? null, warnings: [...norm.warnings] };
    const rule = isIgnoredByPolicy(path, limits.ignorePaths);
    if (rule) {
      const root = ignoredRoot(path, rule);
      const group = ignoredGroups.get(root) || { path: root, status: 'skipped', kind: 'excluded-directory', reason: `Excluded by policy ignorePaths ("${rule}"); contents not inspected.`, count: 0, size: 0, warnings: [] };
      group.count++; group.size += raw.size || 0;
      ignoredGroups.set(root, group);
      continue;
    }
    if (seen.has(path)) { record({ ...base, status: 'skipped', reason: 'Duplicate path: an earlier entry with the same normalized path was kept.' }); continue; }
    seen.set(path, true);
    if (raw.isSymlink) { record({ ...base, status: 'skipped', reason: 'Symbolic link not followed.' }); continue; }
    if (raw.rejectReason) { record({ ...base, status: 'failed', reason: raw.rejectReason }); continue; }
    if (isArchiveExtension(path)) { record({ ...base, kind: 'archive', status: 'skipped', reason: 'Nested archive is inventoried but not extracted.' }); continue; }
    if (isBinaryExtension(path)) { record({ ...base, kind: classifyKind(path, null), status: 'skipped', reason: 'Binary file inventoried for reference checks; content not analyzed.' }); continue; }
    if (raw.size != null && raw.size > limits.maxFileBytes) {
      record({ ...base, kind: classifyKind(path, detectLanguage(path)), language: detectLanguage(path), status: 'skipped', reason: `File is ${raw.size} bytes; the per-file limit is ${limits.maxFileBytes} bytes.` });
      noteLimit('max-file-bytes', `One or more files exceeded the ${limits.maxFileBytes}-byte per-file limit.`);
      continue;
    }
    if (loaded >= limits.maxFiles) {
      record({ ...base, language: detectLanguage(path), kind: classifyKind(path, detectLanguage(path)), status: 'skipped', reason: `File-count limit of ${limits.maxFiles} loaded files reached.` });
      noteLimit('max-files', `Only the first ${limits.maxFiles} text files were loaded (sorted by path).`);
      continue;
    }
    let bytes;
    try {
      const data = raw.text !== undefined ? raw.text : await raw.read();
      bytes = typeof data === 'string' ? textEncoder.encode(data) : data instanceof Uint8Array ? data : new Uint8Array(data);
    } catch (error) {
      const reason = error instanceof ZipError ? `Archive entry rejected: ${error.message}` : `Could not read file: ${error?.message || error}`;
      record({ ...base, status: 'failed', reason });
      continue;
    }
    base.size = bytes.length;
    if (bytes.length > limits.maxFileBytes) { record({ ...base, status: 'skipped', reason: `File is ${bytes.length} bytes; the per-file limit is ${limits.maxFileBytes} bytes.` }); noteLimit('max-file-bytes', `One or more files exceeded the ${limits.maxFileBytes}-byte per-file limit.`); continue; }
    if (totalBytes + bytes.length > limits.maxTotalBytes) {
      record({ ...base, status: 'skipped', reason: `Total loaded size would exceed ${limits.maxTotalBytes} bytes.` });
      noteLimit('max-total-bytes', `Loading stopped adding files after ${totalBytes} bytes (limit ${limits.maxTotalBytes}).`);
      continue;
    }
    const magic = magicType(bytes);
    if (magic || looksBinary(bytes)) {
      const declared = detectLanguage(path);
      record({ ...base, kind: 'binary', status: 'skipped', reason: magic && declared ? `Misleading extension: content is a ${magic}, not ${declared} text.` : `Binary content${magic ? ` (${magic})` : ''}; not analyzed.`, misleadingExtension: Boolean(declared) });
      continue;
    }
    const decoded = decodeText(bytes);
    const language = detectLanguage(path, decoded.text);
    let kind = classifyKind(path, language);
    const warnings = base.warnings;
    if (!decoded.valid) warnings.push('Not valid UTF-8; decoded as Windows-1252. Offsets may differ from the original encoding.');
    if (decoded.encoding.startsWith('utf-16')) warnings.push(`Decoded from ${decoded.encoding.toUpperCase()}.`);
    if (!decoded.text.length) warnings.push('Empty file.');
    if (kind !== 'generated' && language && ['javascript', 'typescript', 'css'].includes(language) && looksMinified(decoded.text)) {
      kind = 'generated';
      warnings.push('Looks minified or machine-generated; excluded from defect rules.');
    } else if (kind !== 'generated' && GENERATED_HEADER.test(decoded.text.slice(0, 600))) {
      kind = 'generated';
      warnings.push('Declares itself generated ("do not edit"); excluded from defect rules.');
    }
    totalBytes += bytes.length;
    loaded++;
    const file = { path, language, kind, content: decoded.text, size: bytes.length, encoding: decoded.encoding };
    files.push(file);
    manifest.push({ ...base, language, kind, status: 'ingested', reason: '', encoding: decoded.encoding, warnings });
  }
  for (const group of ignoredGroups.values()) manifest.push(group);
  const byLower = new Map();
  for (const f of files) {
    const key = f.path.toLowerCase();
    byLower.set(key, [...(byLower.get(key) || []), f.path]);
  }
  const caseCollisions = [...byLower.values()].filter(list => list.length > 1);
  for (const list of caseCollisions) for (const p of list) manifest.find(m => m.path === p)?.warnings.push(`Path differs only by letter case from ${list.filter(x => x !== p).join(', ')}.`);
  manifest.sort((a, b) => a.path.localeCompare(b.path));
  files.sort((a, b) => a.path.localeCompare(b.path));
  onProgress?.({ phase: 'ingest', done: entries.length, total: entries.length });
  return { files, manifest, limits: limitEvents, caseCollisions, source, totalBytes, limitsApplied: limits };
}

export async function ingestZip(bytes, { policy = {}, signal, onProgress, zipLimits = {} } = {}) {
  const data = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes);
  const directory = readZipDirectory(data, zipLimits);
  const limits = ingestionLimits(policy);
  const raw = directory.entries.map(entry => ({
    path: entry.rawName,
    size: entry.uncompressedSize,
    isDirectory: entry.isDirectory,
    isSymlink: entry.isSymlink,
    rejectReason: entry.isDirectory || entry.isSymlink ? null : entryRisk(entry, zipLimits),
    read: () => extractEntry(data, entry, { maxBytes: limits.maxFileBytes }),
  }));
  raw.sort((a, b) => String(a.path).localeCompare(String(b.path)));
  const result = await ingestEntries(raw, { policy, signal, onProgress, source: 'zip' });
  result.archive = { entries: directory.entries.length, zip64: directory.zip64, declaredUncompressed: directory.declaredTotal, issues: directory.issues };
  return result;
}

// Wraps already-loaded text files (editor workspace, demo project, CLI walk).
export function ingestTextFiles(files, { manifestExtra = [] } = {}) {
  const out = [], manifest = [...manifestExtra];
  for (const f of files) {
    const norm = normalizePath(f.path);
    if (!norm.ok) { manifest.push({ path: String(f.path), status: 'skipped', reason: `Unsafe path: ${norm.reason}`, warnings: [] }); continue; }
    const language = f.language && f.language !== 'cpp' ? (detectLanguage(norm.path, f.content) || f.language) : detectLanguage(norm.path, f.content) || f.language || null;
    let kind = f.kind || classifyKind(norm.path, language);
    const warnings = [...norm.warnings];
    if (kind !== 'generated' && ['javascript', 'typescript', 'css'].includes(language) && looksMinified(f.content)) { kind = 'generated'; warnings.push('Looks minified or machine-generated; excluded from defect rules.'); }
    out.push({ path: norm.path, language, kind, content: String(f.content ?? ''), size: textEncoder.encode(String(f.content ?? '')).length, encoding: 'utf-8' });
    manifest.push({ path: norm.path, language, kind, status: 'ingested', reason: '', size: out[out.length - 1].size, warnings });
  }
  manifest.sort((a, b) => a.path.localeCompare(b.path));
  return { files: out, manifest, limits: [], caseCollisions: [], source: 'workspace' };
}

export function projectNameFrom(files, fallback = 'Untitled project') {
  const pkg = files.find(f => basename(f.path) === 'package.json' && !f.path.includes('/node_modules/'));
  if (pkg) { try { const name = JSON.parse(pkg.content).name; if (typeof name === 'string' && name) return name; } catch { /* ignored */ } }
  const py = files.find(f => basename(f.path) === 'pyproject.toml');
  const m = py?.content.match(/^\s*name\s*=\s*["']([^"']+)["']/m);
  if (m) return m[1];
  const roots = new Set(files.map(f => f.path.split('/')[0]));
  if (roots.size === 1 && files.every(f => f.path.includes('/'))) return [...roots][0];
  return fallback;
}
